// Low stock alert content
private javax.swing.JPanel lowStockPanel() {
    final java.awt.Color TEXT_PRIMARY = new java.awt.Color(230, 235, 245);
    final java.awt.Color TEXT_SECOND  = new java.awt.Color(190, 198, 220);
    final java.awt.Font COUNT_FONT = new java.awt.Font("Montserrat", java.awt.Font.PLAIN, 32);
    final java.awt.Font BRAND_FONT = new java.awt.Font("Montserrat", java.awt.Font.PLAIN, 18);

    // Margin between alerts
    final int ALERT_GAP = 22;

    javax.swing.JPanel p = new javax.swing.JPanel();
    p.setOpaque(false);
    p.setLayout(new javax.swing.BoxLayout(p, javax.swing.BoxLayout.Y_AXIS));
    p.setBorder(javax.swing.BorderFactory.createEmptyBorder(8, 0, 8, 0));

    java.util.function.BiConsumer<String, Integer> addRow = (brand, units) -> {
        javax.swing.JPanel row = new javax.swing.JPanel();
        row.setOpaque(false);
        row.setLayout(new javax.swing.BoxLayout(row, javax.swing.BoxLayout.Y_AXIS));
        row.setAlignmentX(LEFT_ALIGNMENT);
        row.setBorder(javax.swing.BorderFactory.createEmptyBorder(0, 0, 10, 0));

        javax.swing.JLabel count = new javax.swing.JLabel(units + " units left");
        count.setFont(COUNT_FONT);
        count.setForeground(TEXT_PRIMARY);
        count.setBorder(javax.swing.BorderFactory.createEmptyBorder(0, 0, 2, 0));

        javax.swing.JLabel brandLab = new javax.swing.JLabel(brand);
        brandLab.setFont(BRAND_FONT);
        brandLab.setForeground(TEXT_SECOND);

        row.add(count);
        row.add(brandLab);
        p.add(row);
        p.add(javax.swing.Box.createVerticalStrut(ALERT_GAP));
    };

    addRow.accept("Volkswagen", 44);
    addRow.accept("Honda", 53);
    addRow.accept("Tesla", 45);

    if (p.getComponentCount() > 0) {
        p.remove(p.getComponentCount() - 1);
    }

    return p;
}

// Rounded panel
private static class RoundedPanel extends javax.swing.JPanel {
    private final int arc; private final java.awt.Color bg;
    RoundedPanel(int arc, java.awt.Color bg) { this.arc = arc; this.bg = bg; setOpaque(false); }
    @Override protected void paintComponent(java.awt.Graphics g) {
        java.awt.Graphics2D g2 = (java.awt.Graphics2D) g.create();
        g2.setRenderingHint(java.awt.RenderingHints.KEY_ANTIALIASING, java.awt.RenderingHints.VALUE_ANTIALIAS_ON);
        g2.setColor(bg);
        g2.fillRoundRect(0, 0, getWidth(), getHeight(), arc, arc);
        g2.dispose();
        super.paintComponent(g);
    }
    @Override public boolean isOpaque() { return false; }
}

