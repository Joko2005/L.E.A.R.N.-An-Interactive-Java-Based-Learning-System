// Populate Placeholders
private void populateDashboard() {
    // Charts
    addChartCardTo(pnlInventory, ChartFactoryUtil.createInventoryBarChart(SampleData.getInventoryDataset()), "Inventory Levels per Category");
    addChartCardTo(pnlTrend,     ChartFactoryUtil.createMonthlyLineChart(SampleData.getMonthlyTrendDataset()), "Monthly Sales Trend");
    addChartCardTo(pnlPie,       ChartFactoryUtil.createSalesPieChart(SampleData.getSalesPieDataset()), "Sales by Product");

    // Info cards
    addPanelCardTo(pnlKpi,   kpiPanel(), "KPI Summary");
    addPanelCardTo(pnlRecs,  recommendationsPanel(), "Recommendations");
    addPanelCardTo(pnlReport, monthlyReportPanel(), "Monthly Report");
    addPanelCardTo(pnlLow,   lowStockPanel(), "Low Stock Alert");
}

// Wrap a chart in a titled rounded card and add to target panel
private void addChartCardTo(JPanel target, JFreeChart chart, String title) {
    target.removeAll();
    ChartPanel cp = ChartFactoryUtil.createChartPanel(chart, target.getWidth(), target.getHeight());
    cp.setOpaque(false);
    cp.setBorder(null);
    target.setLayout(new BorderLayout());
    target.add(card(title, cp, target.getWidth(), target.getHeight()), BorderLayout.CENTER);
    target.revalidate();
    target.repaint();

    target.addComponentListener(new java.awt.event.ComponentAdapter() {
        @Override public void componentResized(java.awt.event.ComponentEvent e) {
            cp.setPreferredSize(target.getSize());
            target.revalidate();
        }
    });
}

// Wrap a regular panel in a rounded card
private void addPanelCardTo(JPanel target, JPanel content, String title) {
    target.removeAll();
    target.setLayout(new BorderLayout());
    target.add(card(title, content, target.getWidth(), target.getHeight()), BorderLayout.CENTER);
    target.revalidate();
    target.repaint();
}
    
// Rounded card
private javax.swing.JPanel card(String title, java.awt.Component center, int w, int h) {
    JPanel p = new RoundedPanel(16, CARD_BG);
    p.setLayout(new java.awt.BorderLayout());
    p.setPreferredSize(new java.awt.Dimension(w, h));
    p.setBorder(javax.swing.BorderFactory.createEmptyBorder(16, 20, 16, 20));

    if (title != null && !title.isEmpty()) {
        javax.swing.JLabel lab = new javax.swing.JLabel(title);
        lab.setForeground(new java.awt.Color(235, 235, 245));
        lab.setFont(CARD_TITLE_FONT);
        lab.setBorder(javax.swing.BorderFactory.createEmptyBorder(0, 0, 6, 0));
        p.add(lab, java.awt.BorderLayout.NORTH);
    }

    javax.swing.JPanel inner = new javax.swing.JPanel(new java.awt.BorderLayout());
    inner.setOpaque(false);
    inner.add(center, java.awt.BorderLayout.CENTER);
    p.add(inner, java.awt.BorderLayout.CENTER);
    return p;
}

